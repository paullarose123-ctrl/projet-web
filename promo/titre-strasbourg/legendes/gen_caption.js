const opentype=require('opentype.js');const fs=require('fs');
const [,, text='10 000 mammifères', sizeArg='150', out='caption'] = process.argv;
const size=+sizeArg, s=size/230;
const font=opentype.loadSync('caprasimo.ttf');
const gl=font.stringToGlyphs(text), sc=size/font.unitsPerEm;
let x=0;const items=[];
gl.forEach((g,i)=>{items.push({ch:text[i],g,x});let adv=g.advanceWidth*sc;if(i<gl.length-1)adv+=font.getKerningValue(g,gl[i+1])*sc;x+=adv;});
const baseline=size*1.05;
const glyphs=items.filter(it=>it.ch!==' ').map(it=>{const p=it.g.getPath(it.x,baseline,size);const bb=p.getBoundingBox();return {d:p.toPathData(2),bb:[bb.x1,bb.y1,bb.x2,bb.y2]};});
const pad=Math.ceil(13*s+3*s+10);
const x1=Math.min(...glyphs.map(g=>g.bb[0]))-pad,x2=Math.max(...glyphs.map(g=>g.bb[2]))+pad;
const y1=Math.min(...glyphs.map(g=>g.bb[1]))-pad,y2=Math.max(...glyphs.map(g=>g.bb[3]))+pad;
const W=Math.ceil((x2-x1)/2)*2,H=Math.ceil((y2-y1)/2)*2;
const vb=[Math.floor(x1),Math.floor(y1),W,H];
let t=fs.readFileSync('template_caption.html','utf8');
t=t.replace('/*GLYPHS*/',JSON.stringify(glyphs)).replace(/\/\*VB\*\//g,vb.join(' ')).replace('/*W*/',W).replace('/*H*/',H).replace('/*S*/',s);
fs.writeFileSync(out+'.html',t);
fs.writeFileSync(out+'.json',JSON.stringify({W,H,vb,n:glyphs.length}));
console.log(JSON.stringify({W,H,vb,n:glyphs.length}));
